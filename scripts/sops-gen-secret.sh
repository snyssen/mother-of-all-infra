#!/usr/bin/env bash
# sops-gen-secret.sh
# Generate new random secrets straight into a SOPS file, without the values ever being
# printed, written to disk in plaintext, or passed on a command line. The counterpart of
# sops-from-vault.sh for secrets that have no legacy value to carry over.
#
# Usage: ./scripts/sops-gen-secret.sh [--length N] <sops-file> <sops/key/path>
#        ./scripts/sops-gen-secret.sh --oidc-client <sops-file> <sops/key/prefix>
#
# The first form writes one random alphanumeric value, 64 characters unless --length says
# otherwise (for consumers that insist on a size, e.g. Uptime Kuma's 32-character push
# tokens). The second writes an
# Authelia OIDC client under <prefix>: `client_id`, `client_secret`, and the
# `client_secret_hash` Authelia's own client config takes (pbkdf2-sha512, generated by
# the authelia CLI together with the secret, so the plaintext is never an argument).
#
# Existing keys are never overwritten — rotating a secret is a deliberate act, done with
# `just sops-update`. The SOPS file is created from .sops.yaml's rules if needed.
# Never run this under `bash -x`: tracing would print the variables holding the values.

set -euo pipefail

GREEN='\033[0;32m'
RED='\033[0;31m'
BOLD='\033[1m'
NC='\033[0m'

usage() {
  echo "Usage: $0 [--length N | --oidc-client] <sops-file> <sops/key/path>" >&2
  exit 2
}

OIDC=0
LENGTH=64
if [ "${1:-}" = "--oidc-client" ]; then OIDC=1; shift
elif [ "${1:-}" = "--length" ]; then
  [[ "${2:-}" =~ ^[1-9][0-9]*$ ]] || usage
  LENGTH=$2; shift 2
fi
[ $# -eq 2 ] || usage
SOPS_FILE=$1
PATH_ARG=$2
[[ "$PATH_ARG" =~ ^[A-Za-z0-9_.-]+(/[A-Za-z0-9_.-]+)*$ ]] || { echo "Invalid sops key path: $PATH_ARG" >&2; exit 2; }

cd "$(git rev-parse --show-toplevel)"

for tool in sops authelia; do
  command -v "$tool" >/dev/null || { echo "$tool not found — run this from the devshell." >&2; exit 1; }
done

to_index() {
  local index="" segment
  IFS=/ read -ra segments <<<"$1"
  for segment in "${segments[@]}"; do index+="[\"$segment\"]"; done
  printf '%s' "$index"
}

if [ "$OIDC" -eq 1 ]; then
  KEYS=("$PATH_ARG/client_id" "$PATH_ARG/client_secret" "$PATH_ARG/client_secret_hash")
else
  KEYS=("$PATH_ARG")
fi

if [ -f "$SOPS_FILE" ]; then
  existing=0
  for key in "${KEYS[@]}"; do
    if sops decrypt --extract "$(to_index "$key")" "$SOPS_FILE" >/dev/null 2>&1; then
      echo -e "${RED}✗${NC} $key already exists in $SOPS_FILE — not overwriting" >&2
      existing=1
    fi
  done
  [ "$existing" -eq 0 ] || exit 1
else
  mkdir -p "$(dirname "$SOPS_FILE")"
  printf '{}\n' | sops encrypt --filename-override "$SOPS_FILE" --input-type yaml --output-type yaml /dev/stdin >"$SOPS_FILE.tmp"
  mv "$SOPS_FILE.tmp" "$SOPS_FILE"
  echo -e "${GREEN}+${NC} created $SOPS_FILE"
fi

random_alnum() { authelia crypto rand --length "$1" --charset alphanumeric | sed -n 's/^Random Value: //p'; }

# Every generated value is alphanumeric or an Authelia digest ([A-Za-z0-9$./+=-]), so
# wrapping it in double quotes is already valid JSON for `sops set`. Checked rather than
# assumed, since a value outside that set would be silently mangled.
set_value() {
  local key=$1 value=$2
  [[ "$value" =~ ^[A-Za-z0-9\$./+=-]+$ ]] || { echo -e "${RED}✗${NC} $key: generated value has an unexpected shape, nothing written" >&2; exit 1; }
  printf '"%s"' "$value" | sops set --value-stdin "$SOPS_FILE" "$(to_index "$key")"
  echo -e "${GREEN}✓${NC} generated ${BOLD}$key${NC}"
}

if [ "$OIDC" -eq 1 ]; then
  CLIENT_ID=$(random_alnum 32)
  GENERATED=$(authelia crypto hash generate pbkdf2 --variant sha512 --random --random.length 72 --random.charset alphanumeric)
  trap 'unset CLIENT_ID GENERATED SECRET DIGEST' EXIT
  SECRET=$(printf '%s\n' "$GENERATED" | sed -n 's/^Random Password: //p')
  DIGEST=$(printf '%s\n' "$GENERATED" | sed -n 's/^Digest: //p')
  [ -n "$CLIENT_ID" ] && [ -n "$SECRET" ] && [ -n "$DIGEST" ] || { echo "Could not parse authelia's output, nothing written." >&2; exit 1; }
  set_value "${KEYS[0]}" "$CLIENT_ID"
  set_value "${KEYS[1]}" "$SECRET"
  set_value "${KEYS[2]}" "$DIGEST"
else
  VALUE=$(random_alnum "$LENGTH")
  trap 'unset VALUE' EXIT
  [ -n "$VALUE" ] || { echo "Could not parse authelia's output, nothing written." >&2; exit 1; }
  set_value "${KEYS[0]}" "$VALUE"
fi
